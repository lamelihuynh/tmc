package vn.tmc.gatestation.adapter.in.rest;

import com.fasterxml.jackson.annotation.JsonProperty;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import java.time.Instant;
import java.util.List;
import java.util.UUID;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;
import vn.tmc.gatestation.application.port.in.IGateAccess;
import vn.tmc.gatestation.application.port.in.IGateAccess.Outcome;
import vn.tmc.gatestation.application.port.in.IGateAccess.ScanRequest;
import vn.tmc.gatestation.application.port.in.IGateAccess.ScanResult;
import vn.tmc.gatestation.application.port.in.IKioskSupport;
import vn.tmc.gatestation.application.port.in.IKioskSupport.Heartbeat;
import vn.tmc.gatestation.application.port.in.IKioskSupport.OfflineEntry;
import vn.tmc.gatestation.application.port.in.IKioskSupport.OfflineEntryResult;
import vn.tmc.gatestation.domain.Direction;
import vn.tmc.platform.kernel.ReasonCode;

/**
 * Kiosk-facing API of the Edge Gateway (document.md table 16.2). Kiosks authenticate with mTLS at
 * the gateway; the Idempotency-Key header IS the attempt id (UUID v7 generated by the kiosk
 * journal).
 */
@RestController
public class KioskController {
  private final IGateAccess access;
  private final IKioskSupport support;

  public KioskController(IGateAccess access, IKioskSupport support) {
    this.access = access;
    this.support = support;
  }

  public record ScanBody(
      @JsonProperty("gate_id") @NotBlank String gateId,
      @JsonProperty("qr_token") @NotBlank String qrToken,
      @JsonProperty("scanned_at") @NotNull Instant scannedAt,
      @JsonProperty("journal_seq") Long journalSeq) {}

  public record ScanResponse(
      @JsonProperty("attempt_id") UUID attemptId,
      Outcome outcome,
      @JsonProperty("reason_code") ReasonCode reasonCode,
      Direction direction,
      boolean duplicate) {}

  @PostMapping("/kiosk/v1/scans")
  public ResponseEntity<ScanResponse> scan(
      @RequestHeader("Idempotency-Key") UUID attemptId,
      @RequestHeader("X-Kiosk-Id") String kioskId,
      @RequestHeader(value = "X-Correlation-Id", required = false) String correlationId,
      @Valid @RequestBody ScanBody body) {
    ScanResult r =
        access.scan(
            new ScanRequest(
                attemptId,
                body.gateId(),
                body.qrToken(),
                body.scannedAt(),
                kioskId,
                correlationId));
    var response =
        new ScanResponse(r.attemptId(), r.outcome(), r.reason(), r.direction(), r.duplicate());
    var status =
        switch (r.outcome()) {
          case ALLOWED, UNCONFIRMED -> HttpStatus.OK;
          case DENIED -> HttpStatus.UNPROCESSABLE_ENTITY;
          case PENDING, IN_PROGRESS -> HttpStatus.ACCEPTED;
        };
    return ResponseEntity.status(status).body(response);
  }

  public record OfflineBody(@NotBlank String kioskId, @NotNull List<@Valid OfflineLine> records) {}

  public record OfflineLine(
      @NotNull UUID attemptId,
      long journalSeq,
      UUID employeeUuid,
      @NotBlank String gateId,
      Direction direction,
      String jti,
      @NotNull Instant scannedAt,
      @NotBlank String localStatus,
      ReasonCode deniedReason) {}

  @PostMapping("/kiosk/v1/scans/offline-batch")
  public List<OfflineEntryResult> offlineBatch(@Valid @RequestBody OfflineBody body) {
    var entries =
        body.records().stream()
            .map(
                l ->
                    new OfflineEntry(
                        l.attemptId(),
                        l.journalSeq(),
                        l.employeeUuid(),
                        l.gateId(),
                        l.direction(),
                        l.jti(),
                        l.scannedAt(),
                        l.localStatus(),
                        l.deniedReason()))
            .toList();
    return support.ingestOffline(body.kioskId(), entries);
  }

  @GetMapping("/kiosk/v1/sync-bundle")
  public IKioskSupport.SyncBundle syncBundle(@RequestParam(required = false) Instant since) {
    return support.syncBundle(since == null ? Instant.EPOCH : since);
  }

  public record HeartbeatBody(
      @NotBlank String kioskId,
      @NotBlank String gateId,
      String readerStatus,
      int offlineQueueSize,
      String softwareVersion) {}

  @PostMapping("/kiosk/v1/heartbeats")
  @ResponseStatus(HttpStatus.NO_CONTENT)
  public void heartbeat(@Valid @RequestBody HeartbeatBody b) {
    support.heartbeat(
        new Heartbeat(
            b.kioskId(), b.gateId(), b.readerStatus(), b.offlineQueueSize(), b.softwareVersion()));
  }
}
